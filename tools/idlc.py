DEFAULT_OUT = ROOT / "generated"
DOC_PATH = ROOT / "docs" / "api_v1.md"

HEADER = "// GENERATED by tools/idlc.py from idl/cabin.yaml \u2014 do not edit\n"

CPP_SCALAR = {
    "u8": "std::uint8_t",
    "u16": "std::uint16_t",
    "u32": "std::uint32_t",
    "u64": "std::uint64_t",
    "i32": "std::int32_t",
    "f32": "float",
    "f64": "double",
    "bool": "bool",
    "string": "std::string",
}

APPEND = {
    "u8": "append_u8",
    "u16": "append_u16",
    "u32": "append_u32",
    "u64": "append_u64",
    "i32": "append_i32",
    "f32": "append_f32",
    "f64": "append_f64",
    "string": "append_string",
}

READ = {
    "u8": "read_u8",
    "u16": "read_u16",
    "u32": "read_u32",
    "u64": "read_u64",
    "i32": "read_i32",
    "f32": "read_f32",
    "f64": "read_f64",
    "string": "read_string",
}

INTEGER_LIMITS = {
    "u8": (0, 255),
    "u16": (0, 65535),
    "u32": (0, 4294967295),
    "u64": (0, 18446744073709551615),
    "i32": (-2147483648, 2147483647),
}


def die(message: str) -> "NoReturn":
    print(f"idlc: error: {message}", file=sys.stderr)
    raise SystemExit(2)


def struct_order(idl: Dict[str, Any]) -> List[str]:
    """Dependency order: nested structs must be complete before their users."""
    deps: Dict[str, List[str]] = {}
    for name, struct in idl["structs"].items():
        deps[name] = [
            field["type"].split(":", 1)[1]
            for field in struct.get("fields", [])
            if field["type"].startswith("struct:")
        ]
    ordered: List[str] = []
    remaining = set(deps)
    while remaining:
        ready = sorted(n for n in remaining if all(d in ordered for d in deps[n]))
        if not ready:
            die("cyclic struct dependency in IDL")
        ordered.extend(ready)
        remaining -= set(ready)
    return ordered


def snake(name: str) -> str:
    out = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    return out.replace("__", "_")


def camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)


def cpp_type(type_name: str) -> str:
    if type_name in CPP_SCALAR:
        return CPP_SCALAR[type_name]
    if type_name.startswith("enum:"):
        return type_name.split(":", 1)[1]
    if type_name.startswith("struct:"):
        return type_name.split(":", 1)[1]
    die(f"unknown field type {type_name}")
    raise AssertionError


def is_unsigned(type_name: str) -> bool:
    return type_name.startswith("u")


def is_float(type_name: str) -> bool:
    return type_name in ("f32", "f64")


def literal(value: Any, type_name: str) -> str:
    if is_float(type_name):
        text = repr(float(value))
        if "e" not in text and "." not in text:
            text += ".0"
        return text + ("F" if type_name == "f32" else "")
    if type_name == "u64":
        return f"{int(value)}ULL"
    return str(int(value))


def enum_bounds(idl: Dict[str, Any], type_name: str) -> Tuple[int, int]:
    name = type_name.split(":", 1)[1]
    return 0, len(idl["enums"][name]) - 1


def field_bounds(idl: Dict[str, Any], field: Dict[str, Any]) -> Optional[Tuple[int, int]]:
    type_name = field["type"]
    if type_name.startswith("enum:"):
        return enum_bounds(idl, type_name)
    if type_name in ("bool", "string") or type_name.startswith("struct:"):
        return None
    if "min" in field and "max" in field:
        return field["min"], field["max"]
    return None


def field_const_type(type_name: str) -> str:
    if type_name.startswith("enum:"):
        return "std::uint8_t"
    if type_name == "string":
        return "std::size_t"
    return cpp_type(type_name)


def default_literal(field: Dict[str, Any], bounds: Optional[Tuple[Any, Any]] = None) -> str:
    type_name = field["type"]
    if "default" in field:
        if type_name == "string":
            return json.dumps(field["default"])
        return literal(field["default"], type_name)
    if type_name == "string":
        return "{}"
    if type_name == "bool":
        return "false"
    if type_name.startswith("enum:"):
        return "static_cast<" + cpp_type(type_name) + ">(0)"
    if type_name.startswith("struct:"):
        return "{}"
    if bounds is not None and bounds[0] not in (0, 0.0):
        return literal(bounds[0], type_name)
    return "0"


def validate_idl(idl: Dict[str, Any]) -> None:
    version = idl["version"]
    if "major" not in version or "minor" not in version:
        die("version must contain major and minor")
    if not isinstance(version["major"], int) or not isinstance(version["minor"], int):
        die("version major/minor must be integers")
    for enum_name, values in idl["enums"].items():
        if len(values) == 0 or len(values) > 256:
            die(f"enum {enum_name} must have 1..256 values")
        if len(set(values)) != len(values):
            die(f"enum {enum_name} has duplicate values")
    signal_names = set()
    for signal in idl["signals"]:
        name = signal["name"]
        if name in signal_names:
            die(f"duplicate signal {name}")
        signal_names.add(name)
        can = signal["can"]
        for key in ("frame_id", "byte_offset", "bit_length", "scale", "offset"):
            if key not in can:
                die(f"signal {name} can mapping missing {key}")
        if can["byte_offset"] * 8 + can["bit_length"] > 64:
            die(f"signal {name} exceeds 8-byte CAN payload")
        if can.get("encoding", "uint") not in ("uint", "f32"):
            die(f"signal {name} has unsupported encoding")
        if signal["type"] not in ("u8", "u16", "u32", "f32", "f64") and not signal[
            "type"
        ].startswith("enum:"):
            die(f"signal {name} has unsupported type {signal['type']}")
    struct_names = set(idl["structs"])
    for struct_name, struct in idl["structs"].items():
        seen = set()
        fields = struct.get("fields", [])
        for index, field in enumerate(fields):
            if field["name"] in seen:
                die(f"duplicate field {struct_name}.{field['name']}")
            seen.add(field["name"])
            type_name = field["type"]
            if type_name.startswith("enum:") and type_name.split(":", 1)[1] not in idl[
                "enums"
            ]:
                die(f"unknown enum in {struct_name}.{field['name']}")
            if type_name.startswith("struct:") and type_name.split(":", 1)[1] not in struct_names:
                die(f"unknown struct in {struct_name}.{field['name']}")
            if type_name not in CPP_SCALAR and not (
                type_name.startswith("enum:") or type_name.startswith("struct:")
            ):
                die(f"unknown type {type_name}")
            if field.get("since_minor") and index != len(fields) - 1:
                die(f"{struct_name}.{field['name']}: since_minor requires last field")
            if field.get("since_minor") and field["since_minor"] > version["minor"]:
                die(f"{struct_name}.{field['name']}: since_minor beyond IDL version")
    for service in idl["services"]:
        for collection in ("methods", "events"):
            seen_ids = set()
            seen_names = set()
            for item in service.get(collection, []):
                if item["id"] in seen_ids:
                    die(f"{service['name']} duplicate {collection} id {item['id']}")
                seen_ids.add(item["id"])
                if item["name"] in seen_names:
                    die(f"{service['name']} duplicate {collection} name {item['name']}")
                seen_names.add(item["name"])
            if collection == "methods":
                for method in service.get("methods", []):
                    for key in ("request", "response"):
                        if method[key] not in struct_names:
                            die(f"{service['name']}.{method['name']} unknown {key}")
            else:
                for event in service.get("events", []):
                    if event["type"] not in struct_names:
                        die(f"{service['name']}.{event['name']} unknown event type")


def signal_range(idl: Dict[str, Any], signal: Dict[str, Any]) -> Tuple[Any, Any]:
    if signal["type"].startswith("enum:"):
        low, high = enum_bounds(idl, signal["type"])
        return low, high
    return signal.get("min", 0), signal.get("max", 1)


