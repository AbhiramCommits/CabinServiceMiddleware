def emit_version(idl: Dict[str, Any]) -> str:
    v = idl["version"]
    return (
        HEADER
        + """
#pragma once

#include <cstdint>

namespace cabin::gen {

inline constexpr std::uint8_t kIdlMajor = %d;
inline constexpr std::uint8_t kIdlMinor = %d;
inline constexpr const char* kIdlVersionString = "%d.%d";

}  // namespace cabin::gen
"""
        % (v["major"], v["minor"], v["major"], v["minor"])
    )


def emit_types(idl: Dict[str, Any]) -> str:
    out = [HEADER, "#pragma once\n\n"]
    out.append("#include <cstddef>\n#include <cstdint>\n#include <optional>\n")
    out.append("#include <string>\n#include <string_view>\n\n")
    out.append("namespace cabin::gen {\n\n")

    for enum_name in sorted(idl["enums"]):
        values = idl["enums"][enum_name]
        out.append(f"enum class {enum_name} : std::uint8_t {{\n")
        for index, value in enumerate(values):
            out.append(f"  k{camel(value)} = {index},\n")
        out.append("};\n\n")
        out.append(f"inline const char* to_string({enum_name} value) {{\n")
        out.append("  switch (value) {\n")
        for value in values:
            out.append(f'    case {enum_name}::k{camel(value)}: return "{value}";\n')
        out.append("  }\n  return \"UNKNOWN\";\n}\n\n")
        out.append(
            f"inline std::optional<{enum_name}> {snake(enum_name)}_from_string("
            "std::string_view text) {\n"
        )
        for value in values:
            out.append(
                f'  if (text == "{value}") return {enum_name}::k{camel(value)};\n'
            )
        out.append("  return std::nullopt;\n}\n\n")

    for struct_name in struct_order(idl):
        fields = idl["structs"][struct_name].get("fields", [])
        out.append(f"struct {struct_name} {{\n")
        if not fields:
            out.append("  bool operator==(const " + struct_name + "&) const { return true; }\n")
        for field in fields:
            const_type = field_const_type(field["type"])
            bounds = field_bounds(idl, field)
            if field["type"] == "string":
                out.append(
                    f"  static constexpr std::size_t {field['name']}_max_len = "
                    f"{int(field.get('max_len', 256))};\n"
                )
            elif bounds is not None:
                out.append(
                    f"  static constexpr {const_type} {field['name']}_min = "
                    f"{literal(bounds[0], field['type'])};\n"
                )
                out.append(
                    f"  static constexpr {const_type} {field['name']}_max = "
                    f"{literal(bounds[1], field['type'])};\n"
                )
            if field.get("since_minor"):
                out.append(
                    f"  static constexpr std::uint8_t {field['name']}_since_minor = "
                    f"{int(field['since_minor'])};\n"
                )
            out.append(f"  {cpp_type(field['type'])} {field['name']} = {default_literal(field, field_bounds(idl, field))};\n")
        if fields:
            comparisons = " && ".join(
                f"{field['name']} == other.{field['name']}" for field in fields
            )
            out.append(
                f"\n  bool operator==(const {struct_name}& other) const {{\n"
                f"    return {comparisons};\n  }}\n"
            )
        out.append("};\n\n")

    out.append("}  // namespace cabin::gen\n")
    return "".join(out)


def validate_body(idl: Dict[str, Any], struct_name: str, indent: str = "  ") -> List[str]:
    fields = idl["structs"][struct_name].get("fields", [])
    out: List[str] = []
    for field in fields:
        name = field["name"]
        value = f"value.{name}"
        type_name = field["type"]
        if type_name == "string":
            limit = int(field.get("max_len", 256))
            out.append(
                f"{indent}if (value.{name}.size() > {struct_name}::{name}_max_len) {{\n"
                f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
                f'exceeds {limit} bytes");\n{indent}}}\n'
            )
            continue
        if type_name.startswith("struct:"):
            nested = type_name.split(":", 1)[1]
            out.append(
                f"{indent}{{ auto nested = validate({value}); if (!nested) return nested.error(); }}\n"
            )
            continue
        if type_name == "bool":
            continue
        if type_name.startswith("enum:"):
            high = enum_bounds(idl, type_name)[1]
            out.append(
                f"{indent}if (static_cast<unsigned>({value}) > {high}u) {{\n"
                f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
                f'is not a valid {type_name.split(":", 1)[1]}");\n{indent}}}\n'
            )
            continue
        if is_float(type_name):
            bounds = field_bounds(idl, field)
            if bounds is None:
                out.append(
                    f"{indent}if (!std::isfinite({value})) {{\n"
                    f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
                    f'must be finite");\n{indent}}}\n'
                )
                continue
            low, high = bounds
            out.append(
                f"{indent}if (!std::isfinite({value}) || {value} < "
                f"{struct_name}::{name}_min || {value} > {struct_name}::{name}_max) {{\n"
                f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
                f'out of range");\n{indent}}}\n'
            )
            continue
        bounds = field_bounds(idl, field)
        if bounds is None:
            continue
        low, high = bounds
        if is_unsigned(type_name):
            if low > 0:
                out.append(
                    f"{indent}if ({value} < {struct_name}::{name}_min) {{\n"
                    f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
                    f'out of range");\n{indent}}}\n'
                )
        else:
            out.append(
                f"{indent}if ({value} < {struct_name}::{name}_min) {{\n"
                f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
                f'out of range");\n{indent}}}\n'
            )
        out.append(
            f"{indent}if ({value} > {struct_name}::{name}_max) {{\n"
            f'{indent}  return make_error(ErrorCode::kOutOfRange, "{struct_name}.{name} '
            f'out of range");\n{indent}}}\n'
        )
    return out


def emit_serdes_header(idl: Dict[str, Any]) -> str:
    out = [
        HEADER,
        "#pragma once\n\n",
        '#include <cstdint>\n\n',
        '#include "cabin/bytes.hpp"\n',
        '#include "cabin/result.hpp"\n',
        '#include "cabin_types.hpp"\n\n',
        "namespace cabin::gen {\n\n",
    ]
    out.append("template <typename T>\nResult<void> validate(const T& value);\n")
    out.append("template <typename T>\nResult<Bytes> encode(const T& value);\n")
    out.append("template <typename T>\nResult<T> decode(Bytes& in);\n")
    out.append("template <typename T>\nResult<T> decode(const Bytes& in);\n\n")
    for struct_name in sorted(idl["structs"]):
        out.append(f"template <>\nResult<void> validate<{struct_name}>(const {struct_name}& value);\n")
        out.append(f"template <>\nResult<Bytes> encode<{struct_name}>(const {struct_name}& value);\n")
        out.append(f"template <>\nResult<{struct_name}> decode<{struct_name}>(Bytes& in);\n")
        out.append(f"template <>\nResult<{struct_name}> decode<{struct_name}>(const Bytes& in);\n\n")
    out.append("\n")
    out.append("}  // namespace cabin::gen\n")
    return "".join(out)


def emit_serdes_cpp(idl: Dict[str, Any]) -> str:
    out = [
        HEADER,
        '#include "cabin_serdes.hpp"\n\n',
        "#include <cmath>\n",
        "#include <cstdint>\n\n",
        "namespace cabin::gen {\n\n",
    ]
    for struct_name in struct_order(idl):
        fields = idl["structs"][struct_name].get("fields", [])
        out.append(f"template <>\nResult<void> validate<{struct_name}>(const {struct_name}& value) {{\n")
        out.append("  (void)value;\n")
        out.extend(validate_body(idl, struct_name))
        out.append("  return ok_status();\n}\n\n")

        out.append(f"template <>\nResult<Bytes> encode<{struct_name}>(const {struct_name}& value) {{\n")
        out.append("  (void)value;\n")
        out.append("  auto status = validate(value);\n")
        out.append("  if (!status) return status.error();\n")
        out.append("  Bytes out;\n")
        out.append(f"  out.reserve({max(8, 8 * len(fields))});\n")
        for field in fields:
            type_name = field["type"]
            if type_name.startswith("struct:"):
                nested = type_name.split(":", 1)[1]
                out.append(f"  {{ auto encoded = encode(value.{field['name']});\n")
                out.append("    if (!encoded) return encoded.error();\n")
                out.append("    if (encoded.value().size() > 0xFFFFu)\n")
                out.append(
                    f'      return make_error(ErrorCode::kOutOfRange, "{struct_name}.{field["name"]} '
                    'nested value too large");\n'
                )
                out.append(
                    f"    out.append_u16(static_cast<std::uint16_t>(encoded.value().size()));\n"
                )
                out.append("    out.append_bytes(encoded.value()); }\n"
                )
                continue
            if type_name.startswith("enum:"):
                out.append(
                    f"  out.append_u8(static_cast<std::uint8_t>(value.{field['name']}));\n"
                )
                continue
            if type_name == "bool":
                out.append(f"  out.append_u8(value.{field['name']} ? 1u : 0u);\n")
                continue
            out.append(f"  out.{APPEND[type_name]}(value.{field['name']});\n")
        out.append("  return out;\n}\n\n")

        out.append(f"template <>\nResult<{struct_name}> decode<{struct_name}>(Bytes& in) {{\n")
        out.append("  (void)in;\n")
        out.append(f"  {struct_name} value{{}};\n")
        for field in fields:
            name = field["name"]
            type_name = field["type"]
            wrapped = bool(field.get("since_minor"))
            if wrapped:
                out.append(f"  if (in.remaining() > 0) {{\n")
            prefix = "    " if wrapped else "  "
            if type_name.startswith("struct:"):
                nested = type_name.split(":", 1)[1]
                out.append(f"{prefix}auto length = in.read_u16();\n")
                out.append(f"{prefix}if (!length) return length.error();\n")
                out.append(f"{prefix}auto nested_bytes = in.read_bytes(length.value());\n")
                out.append(f"{prefix}if (!nested_bytes) return nested_bytes.error();\n")
                out.append(f"{prefix}auto nested = decode<{nested}>(nested_bytes.value());\n")
                out.append(f"{prefix}if (!nested) return nested.error();\n")
                out.append(f"{prefix}value.{name} = nested.value();\n")
            elif type_name == "bool":
                out.append(f"{prefix}auto raw_{name} = in.read_u8();\n")
                out.append(f"{prefix}if (!raw_{name}) return raw_{name}.error();\n")
                out.append(f"{prefix}value.{name} = raw_{name}.value() != 0;\n")
            elif type_name.startswith("enum:"):
                out.append(f"{prefix}auto raw_{name} = in.read_u8();\n")
                out.append(f"{prefix}if (!raw_{name}) return raw_{name}.error();\n")
                out.append(
                    f"{prefix}value.{name} = static_cast<{cpp_type(type_name)}>(raw_{name}.value());\n"
                )
            else:
                out.append(f"{prefix}auto raw_{name} = in.{READ[type_name]}();\n")
                out.append(f"{prefix}if (!raw_{name}) return raw_{name}.error();\n")
                out.append(f"{prefix}value.{name} = raw_{name}.value();\n")
            if wrapped:
                out.append("  }\n")
        out.append("  auto status = validate(value);\n")
        out.append("  if (!status) return status.error();\n")
        out.append("  return value;\n}\n\n")

        out.append(f"template <>\nResult<{struct_name}> decode<{struct_name}>(const Bytes& in) {{\n")
        out.append("  Bytes copy = in;\n")
        out.append(f"  return decode<{struct_name}>(copy);\n}}\n\n")

    out.append("}  // namespace cabin::gen\n")
    return "".join(out)


def emit_services(idl: Dict[str, Any]) -> str:
    out = [
        HEADER,
        "#pragma once\n\n",
        "#include <cstdint>\n\n",
        '#include "cabin/bytes.hpp"\n',
        '#include "cabin/result.hpp"\n',
        '#include "cabin_serdes.hpp"\n',
        '#include "cabin_types.hpp"\n\n',
        "namespace cabin::gen {\n\n",
        "// Transport-agnostic RPC channel. ServiceClient (cabin/client.hpp)\n",
        "// implements this; tests can inject a fake channel.\n",
        "class IRpcChannel {\n public:\n",
        "  virtual ~IRpcChannel() = default;\n",
        "  virtual Result<Bytes> call(std::uint16_t service_id, std::uint16_t method_id,\n",
        "                             const Bytes& request, int timeout_ms) = 0;\n};\n\n",
        "class IService {\n public:\n",
        "  virtual ~IService() = default;\n",
        "  virtual std::uint16_t service_id() const = 0;\n",
        "  virtual const char* service_name() const = 0;\n",
        "  virtual Result<Bytes> dispatch(std::uint16_t method_id,\n",
        "                                 const Bytes& request) = 0;\n};\n\n",
    ]
    for service in idl["services"]:
        name = service["name"]
        sid = int(service["id"])
        out.append(f"inline constexpr std::uint16_t k{name}Id = {sid}u;\n")
        for method in service.get("methods", []):
            out.append(
                f"inline constexpr std::uint16_t k{name}Method{camel(method['name'])} = "
                f"{int(method['id'])}u;\n"
            )
        for event in service.get("events", []):
            out.append(
                f"inline constexpr std::uint16_t k{name}Event{camel(event['name'])} = "
                f"{int(event['id'])}u;\n"
            )
        out.append("\n")

        out.append(f"class I{name} : public IService {{\n public:\n")
        out.append(f"  std::uint16_t service_id() const final {{ return k{name}Id; }}\n")
        out.append(f'  const char* service_name() const final {{ return "{name}"; }}\n')
        out.append("  Result<Bytes> dispatch(std::uint16_t method_id,\n")
        out.append("                         const Bytes& request) final {\n")
        out.append("    switch (method_id) {\n")
        for method in service.get("methods", []):
            req = method["request"]
            resp = method["response"]
            mname = snake(method["name"])
            out.append(f"      case k{name}Method{camel(method['name'])}: {{\n")
            if req == "Empty":
                out.append(f"        auto result = {mname}();\n")
            else:
                out.append(f"        auto decoded = decode<{req}>(request);\n")
                out.append(f"        if (!decoded) return decoded.error();\n")
                out.append(f"        auto result = {mname}(decoded.value());\n")
            out.append("        if (!result) return result.error();\n")
            out.append("        return encode(result.value());\n      }\n")
        out.append("      default:\n")
        out.append(
            f'        return make_error(ErrorCode::kNotFound, "{name} unknown method id");\n'
        )
        out.append("    }\n  }\n\n")
        for method in service.get("methods", []):
            req = method["request"]
            resp = method["response"]
            mname = snake(method["name"])
            if req == "Empty":
                out.append(f"  virtual Result<{resp}> {mname}() = 0;\n")
            else:
                out.append(
                    f"  virtual Result<{resp}> {mname}(const {req}& request) = 0;\n"
                )
        out.append("};\n\n")

        out.append(f"class {name}Client {{\n public:\n")
        out.append(f"  explicit {name}Client(IRpcChannel& channel, int timeout_ms = 1000)\n")
        out.append("      : channel_(channel), timeout_ms_(timeout_ms) {}\n\n")
        for method in service.get("methods", []):
            req = method["request"]
            resp = method["response"]
            mname = snake(method["name"])
            if req == "Empty":
                out.append(f"  Result<{resp}> {mname}() {{\n")
                out.append("    const Empty request{};\n")
            else:
                out.append(f"  Result<{resp}> {mname}(const {req}& request) {{\n")
            out.append("    auto payload = encode(request);\n")
            out.append("    if (!payload) return payload.error();\n")
            out.append(
                f"    auto response = channel_.call(k{name}Id, "
                f"k{name}Method{camel(method['name'])}, payload.value(), timeout_ms_);\n"
            )
            out.append("    if (!response) return response.error();\n")
            out.append(f"    return decode<{resp}>(response.value());\n  }}\n\n")
        out.append(" private:\n  IRpcChannel& channel_;\n  int timeout_ms_;\n};\n\n")

    out.append("}  // namespace cabin::gen\n")
    return "".join(out)


def emit_can_header(idl: Dict[str, Any]) -> str:
    out = [
        HEADER,
        "#pragma once\n\n",
        "#include <cstddef>\n#include <cstdint>\n#include <string_view>\n\n",
        "namespace cabin::signals {\n\n",
        "enum class SignalId : std::uint8_t {\n",
    ]
    for index, signal in enumerate(idl["signals"]):
        out.append(f"  k{camel(signal['name'])} = {index},\n")
    out.append(f"  kCount = {len(idl['signals'])},\n}};\n\n")
    out.append("enum class SignalEncoding : std::uint8_t { kUInt = 0, kFloat32 = 1 };\n\n")
    out.append("struct CanMapping {\n")
    out.append("  std::uint32_t frame_id{0};\n")
    out.append("  std::uint16_t bit_offset{0};\n")
    out.append("  std::uint8_t bit_length{0};\n")
    out.append("  double scale{1.0};\n")
    out.append("  double offset{0.0};\n")
    out.append("  SignalEncoding encoding{SignalEncoding::kUInt};\n};\n\n")
    out.append("struct SignalMeta {\n")
    out.append("  SignalId id{SignalId::kCount};\n")
    out.append('  const char* name{""};\n')
    out.append('  const char* cpp_type{""};\n')
    out.append('  const char* unit{""};\n')
    out.append("  double min{0.0};\n")
    out.append("  double max{0.0};\n")
    out.append("  bool is_enum{false};\n")
    out.append("  CanMapping can{};\n};\n\n")
    out.append(f"inline constexpr std::size_t kSignalCount = {len(idl['signals'])};\n\n")
    out.append("const SignalMeta& signal_meta(SignalId id);\n")
    out.append("const SignalMeta* find_signal(std::string_view name);\n")
    out.append("const char* signal_name(SignalId id);\n")
    out.append("const char* signal_value_name(SignalId id, int value);\n\n")
    out.append("}  // namespace cabin::signals\n")
    return "".join(out)


def emit_can_cpp(idl: Dict[str, Any]) -> str:
    out = [
        HEADER,
        '#include "cabin_can_map.hpp"\n\n',
        "#include <array>\n#include <cstring>\n\n",
        '#include "cabin_types.hpp"\n\n',
        "namespace cabin::signals {\nnamespace {\n\n",
        "constexpr std::array<SignalMeta, kSignalCount> kSignalTable = {{\n",
    ]
    for signal in idl["signals"]:
        low, high = signal_range(idl, signal)
        can = signal["can"]
        is_enum = signal["type"].startswith("enum:")
        out.append(
            "    {SignalId::k%s, \"%s\", \"%s\", \"%s\", %s, %s, %s, "
            "{%du, %du, %du, %s, %s, SignalEncoding::k%s}},\n"
            % (
                camel(signal["name"]),
                signal["name"],
                cpp_type(signal["type"]),
                signal.get("unit", ""),
                repr(float(low)),
                repr(float(high)),
                "true" if is_enum else "false",
                int(can["frame_id"]),
                int(can["byte_offset"]) * 8,
                int(can["bit_length"]),
                repr(float(can["scale"])),
                repr(float(can["offset"])),
                "Float32" if can.get("encoding") == "f32" else "UInt",
            )
        )
    out.append("}};\n\n}  // namespace\n\n")
    out.append("const SignalMeta& signal_meta(SignalId id) {\n")
    out.append("  const auto index = static_cast<std::size_t>(id);\n")
    out.append("  if (index >= kSignalTable.size()) return kSignalTable[0];\n")
    out.append("  return kSignalTable[index];\n}\n\n")
    out.append("const SignalMeta* find_signal(std::string_view name) {\n")
    out.append("  for (const auto& meta : kSignalTable) {\n")
    out.append("    if (name == meta.name) return &meta;\n  }\n  return nullptr;\n}\n\n")
    out.append("const char* signal_name(SignalId id) { return signal_meta(id).name; }\n\n")
    out.append("const char* signal_value_name(SignalId id, int value) {\n")
    out.append("  switch (id) {\n")
    for signal in idl["signals"]:
        if not signal["type"].startswith("enum:"):
            continue
        enum_name = signal["type"].split(":", 1)[1]
        out.append(f"    case SignalId::k{camel(signal['name'])}:\n")
        out.append(f"      return gen::to_string(static_cast<gen::{enum_name}>(value));\n")
    out.append("    default: return \"\";\n")
    out.append("  }\n}\n\n")
    out.append("}  // namespace cabin::signals\n")
    return "".join(out)


def build_schema(idl: Dict[str, Any]) -> Dict[str, Any]:
    enums = {}
    for name in sorted(idl["enums"]):
        enums[name] = {
            "values": idl["enums"][name],
            "values_by_name": {
                value: index for index, value in enumerate(idl["enums"][name])
            },
        }
    signals = []
    for signal in idl["signals"]:
        low, high = signal_range(idl, signal)
        signals.append(
            {
                "name": signal["name"],
                "cpp_name": camel(signal["name"]),
                "type": signal["type"],
                "unit": signal.get("unit", ""),
                "min": low,
                "max": high,
                "enum": signal["type"].split(":", 1)[1]
                if signal["type"].startswith("enum:")
                else None,
                "can": {
                    "frame_id": signal["can"]["frame_id"],
                    "byte_offset": signal["can"]["byte_offset"],
                    "bit_offset": signal["can"]["byte_offset"] * 8,
                    "bit_length": signal["can"]["bit_length"],
                    "scale": signal["can"]["scale"],
                    "offset": signal["can"]["offset"],
                    "encoding": signal["can"].get("encoding", "uint"),
                },
            }
        )
    structs = {}
    for name in sorted(idl["structs"]):
        fields = []
        for field in idl["structs"][name].get("fields", []):
            bounds = field_bounds(idl, field)
            entry = {
                "name": field["name"],
                "type": field["type"],
                "cpp_type": cpp_type(field["type"]),
                "min": bounds[0] if bounds is not None else None,
                "max": bounds[1] if bounds is not None else None,
                "since_minor": field.get("since_minor"),
                "default": field.get("default"),
                "max_len": field.get("max_len"),
            }
            if field["type"].startswith("enum:"):
                entry["enum"] = field["type"].split(":", 1)[1]
            fields.append(entry)
        structs[name] = {"fields": fields}
    services = []
    for service in idl["services"]:
        services.append(
            {
                "name": service["name"],
                "id": service["id"],
                "methods": [
                    {
                        "name": method["name"],
                        "cpp_name": snake(method["name"]),
                        "id": method["id"],
                        "request": method["request"],
                        "response": method["response"],
                    }
                    for method in service.get("methods", [])
                ],
                "events": [
                    {
                        "name": event["name"],
                        "id": event["id"],
                        "type": event["type"],
                    }
                    for event in service.get("events", [])
                ],
            }
        )
    return {
        "schema": "cabin-api",
        "generator": "tools/idlc.py",
        "version": idl["version"],
        "enums": enums,
        "signals": signals,
        "structs": structs,
        "services": services,
    }


def emit_docs(idl: Dict[str, Any]) -> str:
    v = idl["version"]
    lines = [
        "# Cabin IDL API reference (v%d.%d)\n" % (v["major"], v["minor"]),
        "",
        "Generated by `tools/idlc.py` from `idl/cabin.yaml`; do not edit by hand.",
        "",
        "## Version and compatibility\n",
        "",
        f"- Wire major: **{v['major']}**, minor: **{v['minor']}**.",
        "- A frame with a different **major** is rejected with `VERSION_MISMATCH`.",
        "- A higher **minor** is accepted (forward compatible). Additive fields carry",
        "  `since_minor` and must be the last field of their struct so decoders can",
        "  fall back to defaults when an older producer omits them.",
        "",
        "## Signals\n",
        "",
        "| Signal | Type | Range | Unit | CAN frame | Byte | Bits | Scale | Offset |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for signal in idl["signals"]:
        low, high = signal_range(idl, signal)
        can = signal["can"]
        lines.append(
            "| `%s` | `%s` | %s..%s | %s | 0x%03X | %d | %d | %s | %s |"
            % (
                signal["name"],
                signal["type"],
                low,
                high,
                signal.get("unit", ""),
                int(can["frame_id"]),
                int(can["byte_offset"]),
                int(can["bit_length"]),
                can["scale"],
                can["offset"],
            )
        )
    lines += ["", "## Services\n"]
    for service in idl["services"]:
        lines.append(f"### {service['name']} (`0x{int(service['id']):04X}`)\n")
        lines.append("| Kind | Name | Id | Request/Type | Response |")
        lines.append("| --- | --- | --- | --- | --- |")
        for method in service.get("methods", []):
            lines.append(
                f"| method | `{method['name']}` | {method['id']} | "
                f"`{method['request']}` | `{method['response']}` |"
            )
        for event in service.get("events", []):
            lines.append(
                f"| event | `{event['name']}` | {event['id']} | `{event['type']}` | - |"
            )
        lines.append("")
    lines += ["## Structs\n"]
    for struct_name in sorted(idl["structs"]):
        lines.append(f"### `{struct_name}`\n")
        lines.append("| Field | Type | Range | Notes |")
        lines.append("| --- | --- | --- | --- |")
        for field in idl["structs"][struct_name].get("fields", []):
            bounds = field_bounds(idl, field)
            range_text = f"{bounds[0]}..{bounds[1]}" if bounds is not None else "-"
            notes = []
            if field.get("since_minor"):
                notes.append(f"since 1.{field['since_minor']}")
            if field.get("max_len"):
                notes.append(f"max {field['max_len']} bytes")
            lines.append(
                f"| `{field['name']}` | `{field['type']}` | {range_text} | "
                f"{', '.join(notes)} |"
            )
        lines.append("")
    lines += [
        "## Error codes\n",
        "",
        "`OUT_OF_RANGE`, `TRUNCATED`, `BAD_MAGIC`, `BAD_CRC`, `VERSION_MISMATCH`,",
        "`TIMEOUT`, `NOT_FOUND`, `UNAVAILABLE`, `PARSE`, `INTERNAL` (see",
        "`include/cabin/result.hpp`).",
        "",
    ]
    return "\n".join(lines)


def generate(idl: Dict[str, Any], out_dir: Path) -> Dict[str, str]:
    version = idl["version"]
    files = {
        "cabin_version.hpp": emit_version(idl),
        "cabin_types.hpp": emit_types(idl),
        "cabin_serdes.hpp": emit_serdes_header(idl),
        "cabin_serdes.cpp": emit_serdes_cpp(idl),
        "cabin_services.hpp": emit_services(idl),
        "cabin_can_map.hpp": emit_can_header(idl),
        "cabin_can_map.cpp": emit_can_cpp(idl),
        "cabin_schema.json": json.dumps(build_schema(idl), indent=2, sort_keys=True) + "\n",
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out_dir / name).write_text(content, encoding="utf-8")
    return files


def main(argv: Iterable[str]) -> int:
    parser = argparse.ArgumentParser(description="Cabin IDL compiler")
    parser.add_argument("--idl", default=str(DEFAULT_IDL))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--check", action="store_true", help="verify checked-in output")
    args = parser.parse_args(list(argv))

    idl = json.loads(Path(args.idl).read_text(encoding="utf-8"))
    validate_idl(idl)
    docs = emit_docs(idl)

    if args.check:
        out_dir = Path(args.out)
        with tempfile.TemporaryDirectory(prefix="cabinic-check-") as tmp:
            tmp_path = Path(tmp)
            expected = generate(idl, tmp_path)
            problems: List[str] = []
            for name, content in expected.items():
                target = out_dir / name
                if not target.exists():
                    problems.append(f"missing generated/{name}")
                elif target.read_text(encoding="utf-8") != content:
                    problems.append(f"drift in generated/{name}")
            if not DOC_PATH.exists():
                problems.append("missing docs/api_v1.md")
            elif DOC_PATH.read_text(encoding="utf-8") != docs:
                problems.append("drift in docs/api_v1.md")
        if problems:
            for problem in problems:
                print(f"idlc --check: {problem}", file=sys.stderr)
            return 1
        print("idlc --check: generated output is up to date")
        return 0

    out_dir = Path(args.out)
    generate(idl, out_dir)
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(docs, encoding="utf-8")
    print(f"idlc: wrote {len(list(out_dir.iterdir()))} files to {out_dir}")
    print(f"idlc: wrote {DOC_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
