"""Cabin IDL compiler.

Reads idl/cabin.yaml (JSON syntax, a YAML 1.2 subset -- stdlib only) and emits
deterministic C++17 sources, a machine readable schema and the API reference.

Usage:
  tools/idlc.py [--out DIR] [--check]

--check regenerates into a temporary directory and diffs every file, failing if
the checked-in generated output has drifted.
"""

